import SpreadsheetHost from './tools/spreadsheet/SpreadsheetHost';
import PdfToolHost from './tools/pdf/PdfToolHost';
import React from 'react';
import { createRoot } from 'react-dom/client';
import './common/styles.css';
import App from './workspace/App';
import GlobalWheelWindow from './common/GlobalWheelWindow';
import ImageToolHost from './tools/image/ImageToolHost';
import VideoToolHost from './tools/video/VideoToolHost';
import PreviewHost from './action/common/PreviewHost';
import './common/editor.css';
import './tools/image/image-reference.css';
const root = createRoot(document.getElementById('root')!);
const isGlobalWheel = new URLSearchParams(window.location.search).get('santra-wheel') === '1';
const isImageTool = new URLSearchParams(window.location.search).get('santra-image-tool') === '1';
const isVideoTool = new URLSearchParams(window.location.search).get('santra-video-tool') === '1';
const isPdfTool = new URLSearchParams(window.location.search).get('santra-pdf-tool') === '1';
const isSheetTool = new URLSearchParams(window.location.search).get('santra-sheet-tool') === '1';
const isPreview = new URLSearchParams(window.location.search).get('santra-preview') === '1';
if (isGlobalWheel) document.documentElement.classList.add('global-wheel-document');
if (isImageTool) document.documentElement.classList.add('image-tool-document');
if (isVideoTool) document.documentElement.classList.add('video-tool-document');
if (isPdfTool || isSheetTool) document.documentElement.classList.add('compact-tool-document');
root.render(<React.StrictMode>{isSheetTool ? <SpreadsheetHost /> : isPdfTool ? <PdfToolHost /> : isGlobalWheel ? <GlobalWheelWindow /> : isImageTool ? <ImageToolHost /> : isVideoTool ? <VideoToolHost /> : isPreview ? <PreviewHost /> : <App />}</React.StrictMode>);
